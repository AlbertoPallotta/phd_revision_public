on.exit <- NULL
panel <- function(x,dates=as.Date("2026-01-01")+seq_len(nrow(as.matrix(x)))-1L) {
  z <- as.data.table(as.matrix(x));setnames(z,LETTERS[seq_len(ncol(z))]);cbind(data.table(Date=dates),z)
}
fail_expected <- function(expr) inherits(tryCatch(force(expr),error=function(e)e),"error")
warnings_seen <- character()
withCallingHandlers({
  # S1: independently known ratios, distinct from ranks and inverse variance.
  sig <- panel(matrix(c(1,2,4),1));m <- panel(matrix(1,1,3))
  a <- recipes$thesis_a1_legs(m,sig,n=3)
  check("S1_reciprocal",near(mat(a$weights_volatility),matrix(c(4,2,1)/7,1)))
  check("S1_labels",identical(names(a$weights),names(m)) && identical(a$weights$Date,m$Date))
  scaled <- copy(sig);scaled[,c("A","B","C"):=lapply(.SD,function(x)x*7),.SDcols=c("A","B","C")]
  check("S1_scale_invariance",near(mat(recipes$thesis_a1_legs(m,scaled,3)$weights_volatility),mat(a$weights_volatility)))
  rankw <- get("apply_weighting_method",asNamespace("PortfolioTesteR"))(c(A=1,B=2,C=4),method="rank",preference_ascending=TRUE)
  check("S1_rank_oracle",near(rankw,c(3,2,1)/6))
  check("S1_three_methods_distinct",!near(rankw,c(4,2,1)/7) && !near(c(16,4,1)/21,c(4,2,1)/7))
  # S2: selection eligibility and allocation eligibility are separate.
  sig <- panel(matrix(c(0,NA,NaN,Inf,-1,2,4),1));m <- panel(matrix(c(-2,0,NA,Inf,.3,.1,-.1),1))
  a <- recipes$thesis_a1_legs(m,sig)
  check("S2_finite_zero_negative_ranked",identical(as.numeric(mat(a$selected_momentum)),c(1,1,0,0,1,1,1)))
  check("S2_positive_finite_sigma_only",identical(as.numeric(mat(a$selected_volatility)),c(0,0,0,0,0,1,1)))
  check("S2_momentum_independent_of_sigma",near(mat(a$weights_momentum),matrix(c(0,0,0,0,.75,.25,0),1)))
  check("S2_reciprocal_eligibility",near(mat(a$weights_volatility),matrix(c(0,0,0,0,0,2/3,1/3),1)))
  ties <- recipes$thesis_a1_legs(panel(matrix(1,1,7)),panel(matrix(1,1,7)),5)
  check("S2_ties_column_order",identical(as.numeric(mat(ties$selected_union)),c(rep(1,5),0,0)))
  check("S2_unselected_zero",all(mat(ties$weights)[,6:7]==0))
  check("S2_reciprocal_overflow_rejected",fail_expected(recipes$thesis_a1_legs(panel(matrix(1,1,3)),panel(matrix(c(5e-324,1,2),1)),3)))
  check("S2_sum_overflow_rejected",fail_expected(recipes$thesis_a1_legs(panel(matrix(1,1,3)),panel(matrix(c(1e-308,1e-308,1),1)),3)))
  # S3: known rowwise budget and survivor rules.
  mm <- rbind(c(3,0,1),c(3,0,1),rep(NA_real_,3),rep(NA_real_,3))
  ss <- rbind(c(1,2,4),rep(NA_real_,3),c(1,2,4),rep(NA_real_,3))
  a <- recipes$thesis_a1_legs(panel(mm),panel(ss),3)
  expected <- rbind(.6*c(.75,0,.25)+.4*c(4,2,1)/7,c(.75,0,.25),c(4,2,1)/7,c(0,0,0))
  check("S3_blend_and_empty_legs",near(mat(a$weights),expected))
  check("S3_budgets",near(rowSums(mat(a$weights)),c(1,1,1,0)))
  a <- recipes$thesis_a1_legs(panel(matrix(10:1,1)),panel(matrix(10:1,1)))
  check("S3_nonoverlapping_union",sum(mat(a$selected_union))==10)
  a <- recipes$thesis_a1_legs(panel(matrix(10:1,1)),panel(matrix(1:10,1)))
  check("S3_overlapping_union",sum(mat(a$selected_union))==5)
  # S4: population SD from hand-specified simple returns, no annualisation.
  ret <- c(.1,-.1,.2,-.05,.03,.04,.01)
  p <- panel(matrix(100*c(1,cumprod(1+ret)),ncol=1))
  vol <- calc_rolling_volatility(p,lookback=3,method="std")
  oracle <- c(rep(NA_real_,3),vapply(3:length(ret),function(k)sqrt(mean((ret[(k-2):k]-mean(ret[(k-2):k]))^2)),numeric(1)))
  check("S4_population_sd",near(vol$A,oracle))
  broken <- copy(p);broken$A[5] <- NA_real_
  vb <- calc_rolling_volatility(broken,3,"std")
  check("S4_internal_missing_window",all(is.na(vb$A[5:8])))
  dates <- as.Date("2026-01-01")+c(-1,3,3.5,7)
  aligned <- align_to_timeframe(copy(vol),dates,method="forward_fill")
  check("S4_alignment_latest",near(aligned$A,c(NA,oracle[4],oracle[4],oracle[8])))
  ix <- findInterval(as.numeric(dates),as.numeric(p$Date))
  check("S4_no_future_alignment",all(p$Date[ix[ix>0]] <= dates[ix>0]))
  # S5: no input mutation and an independent whole-share/cash toy ledger.
  p2 <- data.table(Date=as.Date("2026-01-01")+c(0,28),A=c(30,33),B=c(20,18))
  w2 <- data.table(Date=p2$Date,A=c(.5,.5),B=c(.5,.5))
  before <- copy(p2)
  bt <- run_backtest(copy(p2),copy(w2),initial_capital=100,name="synthetic S5")
  check("S5_first_allocation",near(mat(bt$positions)[1,],c(1,2)) && near(bt$cash[1],30))
  check("S5_second_allocation",near(mat(bt$positions)[2,],c(1,2)) && near(bt$cash[2],30))
  check("S5_value_accounting",near(bt$portfolio_values,c(100,99)))
  check("S5_input_unmutated",identical(p2,before))
  check("S5_no_extra_dates",identical(as.Date(bt$dates),as.Date(p2$Date)))
  # S6: genuine paired diagnostic; old self-correlation retained as a counterexample.
  fake <- structure(list(optimization_summary=data.frame(Window=1:4,IS_Score=1:4,OOS_Score=4:1)),class="wf_optimization_result")
  pdf(file.path(repdir,"evidence/S6-synthetic-scatter.pdf"))
  corrected <- plot(fake,type="is_oos",metric=c("IS_Score","OOS_Score"))
  default <- plot(fake,type="is_oos")
  old <- plot(fake,type="is_oos",metric="OOS_Score")
  dev.off()
  check("S6_correct_pair",corrected$is_col=="IS_Score" && corrected$oos_col=="OOS_Score" && near(corrected$cor,-1))
  check("S6_default_matches",identical(corrected,default))
  check("S6_old_self_correlation",near(old$cor,1))
  # S7: actual preceding prices supply the endpoint; unused cache is irrelevant.
  toy <- data.frame(Date=as.Date("2026-01-01")+7*(0:77),A=100+0:77,B=200+2*(0:77))
  oos <- toy[53:78,];ext <- toy[27:78,]
  nohist <- recipes$thesis_b3_panels(oos,list(lookback=26,n_top=2))
  withhist <- recipes$thesis_b3_panels(ext,list(lookback=26,n_top=2))
  check("S7_no_history_unavailable",all(is.na(mat(nohist$momentum))) && all(mat(nohist$weights)==0))
  check("S7_genuine_first_endpoint",near(withhist$momentum$A[27],toy$A[53]/toy$A[27]-1))
  check("S7_all_OOS_available",all(is.finite(mat(withhist$momentum)[27:52,])) && all(rowSums(mat(withhist$weights)[27:52,])==1))
  ispan <- recipes$thesis_b3_panels(toy[1:52,],list(lookback=26,n_top=2))
  check("S7_IS_startup_cash",all(mat(ispan$weights)[1:26,]==0) && all(rowSums(mat(ispan$weights)[27:52,])==1))
  check("S7_history_precedes_cutoff",max(ext$Date[1:26])==toy$Date[52] && min(ext$Date[27:52])==toy$Date[53])
  # S8: retained raw duplicate anchor, presentation-only date correction.
  legs <- list(list(dates=as.Date("2026-01-01")+0:2,portfolio_values=c(100,110,121)),
               list(dates=as.Date("2026-01-01")+3:5,portfolio_values=c(100,90,81)))
  st <- wf_stitch(legs,initial_value=100)
  check("S8_compound_oracle",near(st$Value,c(100,110,121,108.9,98.01)))
  check("S8_raw_anchor_duplicate",st$Date[1]==st$Date[2])
  display <- st;display$Date[1] <- legs[[1]]$dates[1]
  check("S8_display_values_identical",identical(display$Value,st$Value) && !anyDuplicated(display$Date))
  check("S8_boundary_interval_omitted",identical(as.Date(st$Date[-1]),as.Date("2026-01-01")+c(1,2,4,5)))
},warning=function(w) {warnings_seen <<- c(warnings_seen,conditionMessage(w));invokeRestart("muffleWarning")})
writeLines(warnings_seen,file.path(repdir,"evidence/synthetic-warnings.txt"))
save_checks("synthetic-checks")
stopifnot(!length(warnings_seen))
