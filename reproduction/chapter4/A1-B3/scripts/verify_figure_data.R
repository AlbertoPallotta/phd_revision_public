source(file.path(Sys.getenv("PT_BUILDER_ROOT"),"thesis-reproduction/scripts/common.R"))
fig<-file.path(repdir,"figures")
scores<-fread(file.path(fig,"B3_heatmap_raw_scores.csv"))
z<-matrix(NA_real_,3,4);xs<-sort(unique(scores$lookback));ys<-sort(unique(scores$n_top))
for(i in seq_len(nrow(scores))) z[match(scores$n_top[i],ys),match(scores$lookback[i],xs)]<-scores$score[i]
labels<-data.frame(lookback=rep(xs,each=3),n_top=rep(ys,times=4),helper_label=as.vector(t(z)),correct_score=as.vector(z))
labels$mismatch<-abs(labels$helper_label-labels$correct_score)>1e-12
pdf(NULL)
old_plot<-plot(readRDS(file.path(repdir,"results/study/B3-grid.rds")),type="heatmap",params=c("lookback","n_top"),clip=c(0,1))
dev.off()
check("heatmap_diagnostic_matches_actual_helper_matrix",near(z,old_plot$grid$z))
fwrite(labels,file.path(repdir,"evidence/heatmap-helper-label-diagnostic.csv"))
check("heatmap_existing_label_issue_demonstrated",any(labels$mismatch))
for(i in seq_len(nrow(scores)))check(paste0("final_heatmap_coordinate_",i),near(scores$score[i],z[match(scores$n_top[i],ys),match(scores$lookback[i],xs)]))
wf<-readRDS(file.path(repdir,"results/study/B3-WF.rds"))
png(file.path(fig,"paired-api-metadata-check.png"));pm<-plot(wf,type="is_oos",metric=c("IS_Score","OOS_Score"));dev.off()
capture.output(str(pm),file=file.path(repdir,"evidence/paired-api-metadata.txt"))
saveRDS(pm,file.path(repdir,"evidence/paired-api-metadata.rds"))
check("final_scatter_four_finite_pairs",sum(is.finite(wf$optimization_summary$IS_Score)&is.finite(wf$optimization_summary$OOS_Score))==4)
check("paired_API_columns",identical(c(pm$is_col,pm$oos_col),c("IS_Score","OOS_Score")))
check("paired_API_correlation",near(pm$cor,cor(wf$optimization_summary$IS_Score,wf$optimization_summary$OOS_Score)))
save_checks("figure-data-checks")
