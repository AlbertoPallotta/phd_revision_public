invisible(dev.off())
pdf(file.path(out,"figures/Figure4_3.pdf"),width=10,height=7,family="Helvetica",useDingbats=FALSE)
figfun("Gross returns; portfolio-only display.")
invisible(dev.off())
stopifnot(identical(before,unname(tools::md5sum(input))))
